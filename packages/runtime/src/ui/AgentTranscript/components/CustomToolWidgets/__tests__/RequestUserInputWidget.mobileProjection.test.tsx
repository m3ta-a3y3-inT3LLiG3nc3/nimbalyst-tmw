import React from 'react';
import { expect, it, vi } from 'vitest';
import { act, fireEvent, render, screen, cleanup } from '@testing-library/react';
import { Provider } from 'jotai';
import { store } from '../../../../../store/store';
import { setInteractiveWidgetHost } from '../../../../../store/atoms/interactiveWidgetHost';
import { clearRequestUserInputDraft, requestUserInputDraftAtom } from '../../../../../store/atoms/requestUserInputDraft';
import { projectRawMessagesToViewMessages } from '../../../../../ai/server/transcript/projectRawMessages';
import { truncateContentForSync } from '../../../../../sync/syncContentTruncator';
import { RequestUserInputWidget } from '../RequestUserInputWidget';
import type { InteractiveWidgetHost } from '../InteractiveWidgetHost';

it.each(['submit', 'cancel'])('#1711 repaired transcript retains draft and original %s identity', async action => {
  const sessionId = `github-1711-${action}`;
  const promptId = `nimtc|call-${action}|0|2`;
  const args = { title: 'Review', fields: [{ id: 'body', label: 'Body', type: 'editText', format: 'plain', initialText: 'Agent draft '.repeat(1800) }] };
  const raw = (id: number, item: Record<string, unknown>) => ({ id, sessionId, source: 'openai-codex', direction: 'output' as const, createdAt: new Date(id), content: JSON.stringify({ method: 'item/started', params: { item } }), metadata: { transport: 'app-server', eventType: 'item/started', editGroupId: promptId } });
  const reply = { ...raw(1, { id: 'reply', type: 'agentMessage', text: 'Complete assistant reply '.repeat(1000) }), metadata: { transport: 'app-server', eventType: 'item/completed' }, content: JSON.stringify({ method: 'item/completed', params: { item: { id: 'reply', type: 'agentMessage', text: 'Complete assistant reply '.repeat(1000) } } }) };
  const question = raw(2, { id: `call-${action}`, type: 'mcpToolCall', server: 'nimbalyst', tool: 'PromptForUserInput', arguments: args });
  const projected = { ...question, content: truncateContentForSync(question.content, question.source).content };
  const legacyReply = { ...reply, content: '[Full openai-codex message elided from mobile sync: 32.1 KB raw. View on desktop for the full content.]' };
  const initial = await projectRawMessagesToViewMessages([legacyReply, projected], 'openai-codex');
  const repaired = await projectRawMessagesToViewMessages([reply, projected], 'openai-codex');
  const initialQuestion = initial.find(message => message.toolCall?.providerToolCallId === promptId)!;
  const repairedQuestions = repaired.filter(message => message.toolCall?.providerToolCallId === promptId);
  expect(repairedQuestions).toHaveLength(1);
  expect(repairedQuestions[0].toolCall?.arguments).toEqual(args);
  clearRequestUserInputDraft(promptId);
  const submit = vi.fn().mockResolvedValue(undefined);
  const cancel = vi.fn().mockResolvedValue(undefined);
  setInteractiveWidgetHost(sessionId, { requestUserInputSubmit: submit, requestUserInputCancel: cancel } as unknown as InteractiveWidgetHost);
  const widget = (message: typeof initialQuestion) => <Provider store={store}><RequestUserInputWidget message={message} sessionId={sessionId} isExpanded onToggle={() => {}} /></Provider>;
  const first = render(widget(initialQuestion));
  await act(async () => {});
  await act(async () => { store.set(requestUserInputDraftAtom(promptId), previous => ({ ...previous, fields: { body: { type: 'editText', state: { text: 'User edits survive repair' } } } })); });
  first.unmount();
  render(widget(repairedQuestions[0]));
  await act(async () => {});
  expect(screen.getByTestId('request-user-input-edittext-content').textContent).toContain('User edits survive repair');
  await act(async () => { fireEvent.click(screen.getByTestId(`request-user-input-${action}`)); });
  if (action === 'submit') expect(submit).toHaveBeenCalledWith(promptId, { body: { type: 'editText', text: 'User edits survive repair', edited: true } });
  else expect(cancel).toHaveBeenCalledWith(promptId);
  cleanup(); clearRequestUserInputDraft(promptId);
});
